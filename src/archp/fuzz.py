"""Random test-program generator for RTL-vs-golden differential testing (T-006+).

Programs are dense in hazards: random register dependencies at short distances,
loads/stores/stack operations interleaved with ALU operations, SWAPs, IN/OUT.
Rules keep them deterministic and free of self-modifying code:

* R7 is a fixed data base pointer (0x800); it is read but never written.
* LDD/STD use ``off(R7)`` with offsets 0..0xFF (data area 0x800..0x8FF).
* The stack depth stays within 0..16, so PUSH never reaches the code.
* Optional features (later tasks): forward branches, CALL/RET, INT.
"""

from __future__ import annotations

import random

ALU3 = ("ADD", "SUB", "AND")
ALU1 = ("NOT", "INC")


def generate(
    seed: int,
    length: int = 60,
    *,
    branches: bool = False,
    calls: bool = False,
    sw_int: bool = False,
    hw_int: bool = False,
) -> str:
    rng = random.Random(seed)  # noqa: S311 (test-program generator)
    regs = [f"R{i}" for i in range(7)]  # destinations R0..R6
    srcs = [f"R{i}" for i in range(8)]

    def r() -> str:
        # bias towards a few registers -> many short-distance dependencies
        return rng.choice(regs[:3]) if rng.random() < 0.6 else rng.choice(regs)

    def s() -> str:
        return rng.choice(srcs[:3]) if rng.random() < 0.6 else rng.choice(srcs)

    lines = ["# generated by archp.fuzz", ".ORG 0", "10"]
    if hw_int:
        lines += [".ORG 1", "700"]
    if sw_int:
        lines += [".ORG 2", "740", "760"]
    lines += [".ORG 10", "LDM R7, 800"]
    lines += [f"LDM {reg}, {rng.getrandbits(16):X}" for reg in regs]
    depth = 0
    label = 0
    pending: list[tuple[int, str]] = []  # (emit before instruction index, label)
    body: list[str] = []
    for i in range(length):
        for at, lab in [p for p in pending if p[0] == i]:
            body.append(f"{lab}:")
            pending.remove((at, lab))
        k = rng.random()
        if k < 0.30:
            body.append(f"{rng.choice(ALU3)} {r()}, {s()}, {s()}")
        elif k < 0.38:
            body.append(f"{rng.choice(ALU1)} {r()}")
        elif k < 0.44:
            body.append(f"IADD {r()}, {s()}, {rng.getrandbits(16):X}")
        elif k < 0.48:
            body.append(f"{rng.choice(('SHL', 'SHR'))} {r()}, {rng.randrange(0, 34):X}")
        elif k < 0.52:
            body.append(f"CMP {s()}, {s()}")
        elif k < 0.56:
            body.append(f"MOV {r()}, {s()}")
        elif k < 0.60:
            body.append(f"SWAP {r()}, {r()}")
        elif k < 0.66:
            body.append(f"LDD {r()}, {rng.randrange(256):X}(R7)")
        elif k < 0.72:
            body.append(f"STD {s()}, {rng.randrange(256):X}(R7)")
        elif k < 0.77 and depth < 16:
            body.append(f"PUSH {s()}")
            depth += 1
        elif k < 0.82 and depth > 0:
            body.append(f"POP {r()}")
            depth -= 1
        elif k < 0.85:
            body.append(f"IN {r()}")
        elif k < 0.88:
            body.append(f"OUT {s()}")
        elif k < 0.90:
            body.append(f"LDM {r()}, {rng.getrandbits(16):X}")
        elif k < 0.92:
            body.append("SETC")
        elif branches and k < 0.97:
            label += 1
            lab = f"L{label}"
            op = rng.choice(("JZ", "JN", "JC", "JZ", "JN", "JC", "JMP"))
            body.append(f"{op} {lab}")
            pending.append((min(length, i + 1 + rng.randrange(0, 4)), lab))
        elif calls and k < 0.985:
            body.append(f"CALL {rng.choice(('F1', 'F2'))}")
        elif sw_int and k < 0.995:
            body.append(f"INT {rng.randrange(2)}")
        else:
            body.append("NOP")
    for _, lab in pending:
        body.append(f"{lab}:")
    lines += body
    lines += [f"OUT R{i}" for i in range(8)]
    lines.append("HLT")
    if calls:  # leaf subroutines with hazards right after entry / before RET
        lines += [".ORG 600", "F1: INC R1", "ADD R2, R1, R2", "RET"]
        lines += [".ORG 620", "F2: PUSH R3", "SHL R3, 1", "POP R4", "RET"]
    if hw_int:  # handler: changes flags and registers, restores them via RTI
        lines += [".ORG 700", "PUSH R0", "LDM R0, 0", "SUB R0, R0, R0", "INC R5", "POP R0", "RTI"]
    if sw_int:
        lines += [".ORG 740", "NOT R6", "RTI", ".ORG 760", "IADD R6, R6, 3", "RTI"]
    inputs = " ".join(f"{rng.getrandbits(32):X}" for _ in range(40))
    lines.insert(1, f"#! in: {inputs}")
    lines.insert(2, "#! max_cycles: 20000")
    return "\n".join(lines) + "\n"
